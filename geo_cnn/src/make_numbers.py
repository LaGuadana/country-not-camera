"""Collect every quotable number from results/*.json into numbers.txt (with its source file).

Usage:
  python -I src/make_numbers.py --results results --processed data/processed --out numbers.txt
"""
import argparse
import json
import os


def load(p):
    if os.path.exists(p):
        with open(p) as f:
            return json.load(f)
    return None


def pct(x):
    return f"{100 * x:.1f}%"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True)
    ap.add_argument("--processed", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    L = []
    add = L.append

    add("# numbers.txt  (generated by src/make_numbers.py; every line: value  [source])")
    add("")
    add("## Dataset (from the Hugging Face repo osv5m/osv5m, https://huggingface.co/datasets/osv5m/osv5m)")
    add("licence: CC-BY-SA-4.0  [HF dataset card YAML `license: cc-by-sa-4.0`; data/raw/README_hf.md]")
    add("reference: Astruc et al., OpenStreetView-5M: The Many Roads to Global Visual Geolocation, CVPR 2024  [README_hf.md]")
    add("files: train.csv 2,915,296,639 B; test.csv 116,469,997 B; images/train/00..97.zip (98 shards); "
        "images/test/00..04.zip (5 shards: 2,251,257,459 / 2,239,571,110 / 2,236,820,013 / 2,246,080,815 / 453,288,134 B)  "
        "[HF API https://huggingface.co/api/datasets/osv5m/osv5m/tree/main/images/test]")
    add("repo total storage: 258,835,496,994 B (~259 GB)  [HF API usedStorage]")

    m = load(os.path.join(a.results, "metadata_stats.json"))
    if m:
        src = "[results/metadata_stats.json, from data/raw/{train,test}.csv]"
        for split in ("train", "test"):
            s = m[split]
            add("")
            add(f"## {split} split metadata")
            add(f"{split} images (rows): {s['n_rows']:,}  {src}")
            add(f"{split} Mapillary sequences: {s['n_sequences']:,}  {src}")
            add(f"{split} countries (distinct `country` codes): {s['n_countries']}  {src}")
            add(f"{split} countries with >=100 / >=1k / >=10k / >=100k images: "
                f"{s['n_countries_ge_100']} / {s['n_countries_ge_1k']} / {s['n_countries_ge_10k']} / {s['n_countries_ge_100k']}  {src}")
            add(f"{split} countries with <100 images: {s['n_countries_lt_100']}  {src}")
            add(f"{split} largest country: {s['top1_country']} with {s['top1_count']:,} images ({pct(s['top1_share'])})  {src}")
            add(f"{split} share of images in top 10 / top 30 countries: {pct(s['top10_share'])} / {pct(s['top30_share'])}  {src}")
            add(f"{split} median images per country: {s['median_count']:,.0f}  {src}")
        add(f"countries in union of train+test: {m['n_countries_union']}  {src}")
        add(f"countries in test but not train: {m['countries_in_test_not_train']}  {src}")
        add(f"countries in train but not test: {len(m['countries_in_train_not_test'])}  {src}")
        add("train top 10: " + ", ".join(f"{c} {n} ({v:,})" for c, n, v in m["top10_train"]) + f"  {src}")
        add(f"world-scatter sample size: {m['coord_sample_n']:,} random train rows  {src}")

    s = load(os.path.join(a.results, "shard_stats.json"))
    if s:
        src = "[results/shard_stats.json, from data/raw/images_test/04.zip + test.csv]"
        add("")
        add("## Downloaded image shard (test split, images/test/04.zip)")
        add(f"zip size: {s['zip_bytes']:,} B  {src}")
        add(f"images in zip: {s['n_images_in_zip']:,}; matched to test.csv: {s['n_matched_to_metadata']:,}  {src}")
        add(f"countries / sequences / creators in shard: {s['n_countries_in_shard']} / {s['n_sequences_in_shard']:,} / {s['n_creators_in_shard']:,}  {src}")
        add(f"width min/median/max: {s['width_min_median_max']}; height min/median/max: {s['height_min_median_max']}  {src}")
        add(f"share landscape (w>h): {pct(s['share_landscape'])}; mean JPEG size: {s['mean_jpeg_kb']:.0f} KB  {src}")
        add("most common resolutions: " + "; ".join(f"{r} {pct(f)}" for r, n, f in s["top_resolutions"][:5]) + f"  {src}")

    ct = os.path.join(a.results, "country_counts_test.csv")
    si = os.path.join(a.processed, "shard_index.csv")
    if os.path.exists(ct) and os.path.exists(si):
        import pandas as pd
        te = pd.read_csv(ct, keep_default_na=False, dtype={"country": str}).set_index("country")["n_images"]
        sh = pd.read_csv(si, keep_default_na=False, dtype=str)["country"].value_counts()
        d = pd.DataFrame({"t": te / te.sum(), "s": sh / sh.sum()}).fillna(0)
        add(f"shard 04 vs full test split country mix: total-variation distance {0.5 * (d.t - d.s).abs().sum():.3f}; "
            f"shard holds {sh.sum() / te.sum():.1%} of test images; same top-10 countries: "
            f"{list(te.sort_values(ascending=False).index[:10]) == list(sh.index[:10])}  "
            f"[src/make_numbers.py from results/country_counts_test.csv + data/processed/shard_index.csv]")

    sp = load(os.path.join(a.results, "split_stats.json"))
    if sp:
        src = "[results/split_stats.json, src/make_split.py]"
        add("")
        add("## Balanced 10-country subset and split")
        add(f"countries: {sp['countries']}  {src}")
        add(f"their counts in the shard: {sp['shard_counts_of_chosen']}  {src}")
        add(f"images per country (balanced): {sp['n_per_class']}; total {sp['n_total']:,}  {src}")
        add(f"train / test images: {sp['n_train']:,} / {sp['n_test']:,}  {src}")
        add(f"per-class test n: {sp['per_class_test']}  {src}")
        add(f"distinct sequences: {sp['n_sequences']:,}; leakage groups (sequence OR {sp['cell_deg']} deg cell): {sp['n_groups']:,}; largest group {sp['largest_group']} images  {src}")
        add(f"groups shared train/test: {sp['groups_shared_train_test']}; sequences shared: {sp['sequences_shared_train_test']}  {src}")
        add(f"photographers (creator_id): {sp['creators_total']}; shared train/test: {sp['creators_shared_train_test']}; "
            f"test images whose photographer also appears in train: {sp['test_images_whose_creator_in_train']}  {src}")

    for tag, label in [("", "sequence- and 0.1 deg cell-disjoint split (MAIN)"),
                       ("_strict", "sequence-, cell- AND photographer-disjoint split (STRICT; test set not balanced)")]:
      b = load(os.path.join(a.results, f"baseline_results{tag}.json"))
      if b:
        src = f"[results/baseline_results{tag}.json, src/baselines.py]"
        add("")
        add(f"## Baselines, {label}: n_train = {b['n_train']}, n_test = {b['n_test']}, 10 classes")
        add(f"test class counts: {b.get('test_class_counts')}  {src}")
        for k, v in b["models"].items():
            line = f"{k}: top-1 {pct(v['top1'])}, top-3 {pct(v['top3'])}"
            if "balanced_top1" in v:
                line += f", balanced top-1 (mean per-class recall) {pct(v['balanced_top1'])}"
            if "top1_ci95" in v:
                line += f" (top-1 95% Wilson CI {pct(v['top1_ci95'][0])}-{pct(v['top1_ci95'][1])})"
            if "best_C" in v:
                line += f"; C={v['best_C']}; grouped 3-fold CV top-1 on train {pct(v['cv_top1_train'])}; dim {v['dim']}"
            add(line + f"  {src}")
            if "per_class_recall" in v:
                add(f"  {k} per-class recall: " + ", ".join(f"{c} {pct(r)}" for c, r in v["per_class_recall"].items()))
    sps = load(os.path.join(a.results, "split_stats_strict.json"))
    if sps:
        src = "[results/split_stats_strict.json, src/make_split.py --group-creator]"
        add(f"strict split: train/test {sps['n_train']}/{sps['n_test']}; groups {sps['n_groups']}; largest group {sps['largest_group']} images; "
            f"photographers shared train/test {sps['creators_shared_train_test']}; per-class test n {sps['per_class_test']}  {src}")

    for kind in ("hsv", "resnet18"):
        t = load(os.path.join(a.processed, f"feat_{kind}_timing.json"))
        if t:
            src = f"[data/processed/feat_{kind}_timing.json, src/features.py]"
            line = (f"{kind} feature extraction: {t['n']} images in {t['seconds']:.0f} s = "
                    f"{t['img_per_s_end_to_end']:.1f} img/s end-to-end (JPEG decode from zip + preprocessing"
                    f"{' + forward' if kind == 'resnet18' else ''}), {t['threads']} threads")
            if "img_per_s_forward_only" in t:
                line += f"; forward pass only {t['img_per_s_forward_only']:.1f} img/s (batch {t['batch']}, 224 px)"
            add(line + f"; CPU shared with a running RL job  {src}")

    log = os.path.join(os.path.dirname(a.processed.rstrip("/")) or ".", "resnet.log")
    if os.path.exists(log):
        import re
        pts = [(int(m.group(1)), int(m.group(1)) / float(m.group(2)))
               for m in re.finditer(r"\s(\d+)/\d+\s+([\d.]+) img/s", open(log).read().replace("\r", "\n"))]
        if len(pts) >= 2:
            (n0, t0), (n1, t1) = pts[0], pts[-1]
            add(f"resnet18 steady-state end-to-end rate (first to last progress line, excludes one-off weight download): "
                f"{(n1 - n0) / (t1 - t0):.1f} img/s  [data/resnet.log progress lines; rates are rounded to 0.1 so +-~0.3 img/s]")
    tr_p = os.path.join(a.results, "country_counts_train.csv")
    if os.path.exists(tr_p) and os.path.exists(ct):
        import pandas as pd
        tr = pd.read_csv(tr_p, keep_default_na=False, dtype={"country": str}).set_index("country")["n_images"]
        te = pd.read_csv(ct, keep_default_na=False, dtype={"country": str}).set_index("country")["n_images"]
        add("")
        add("## Train vs test country shares (prior shift)")
        for c in ["US", "DE", "FR", "RU", "JP", "GB", "AU", "BR", "IN", "CN", "KZ"]:
            add(f"{c}: train {tr.get(c, 0) / tr.sum():.2%} ({tr.get(c, 0):,}) vs test {te.get(c, 0) / te.sum():.2%} ({te.get(c, 0):,})  "
                f"[results/country_counts_train.csv, results/country_counts_test.csv]")
        d = pd.DataFrame({"t": tr / tr.sum(), "e": te / te.sum()}).fillna(0)
        add(f"total-variation distance train vs test country mix: {0.5 * (d.t - d.e).abs().sum():.3f}  [same]")
        add(f"train images for the 10 chosen countries: " + ", ".join(f"{c} {tr.get(c, 0):,}" for c in
            ["US", "RU", "AU", "BR", "CA", "IN", "MX", "CN", "AR", "KZ"]) + "  [results/country_counts_train.csv]")
    add("")
    add("download integrity: SHA-256 of train.csv, test.csv, images/test/04.zip match the HF LFS oids  [data/SHA256SUMS.txt]")

    with open(a.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
